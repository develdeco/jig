// TestLoadConfigCarriesTheProjectsPublishTrailer: the marker's publish:
// trailer: is the config's PublishTrailer, which every rendered pull request
// body ends with. A marker that sets none, and a v2 store (which has no
// marker), leave it empty.
func TestLoadConfigCarriesTheProjectsPublishTrailer(t *testing.T) {
	jigHome := t.TempDir()
	storeDir := t.TempDir()
	writeFile(t, filepath.Join(storeDir, "store.yaml"), v3StoreYAML)

	for name, tc := range map[string]struct {
		publish *Publish
		want    string
	}{
		"set":        {&Publish{Trailer: "Generated by an agent"}, "Generated by an agent"},
		"multi-line": {&Publish{Trailer: "one\ntwo"}, "one\ntwo"},
		"empty":      {&Publish{}, ""},
		"no publish": {nil, ""},
	} {
		root := t.TempDir()
		if err := WriteMarker(root, Marker{Jig: "1", Project: "demo", Kind: KindProject, Publish: tc.publish}); err != nil {
			t.Fatal(err)
		}
		cfg, err := LoadConfig(jigHome, storeDir, "", root)
		if err != nil {
			t.Fatal(err)
		}
		if cfg.PublishTrailer != tc.want {
			t.Errorf("%s: PublishTrailer = %q, want %q", name, cfg.PublishTrailer, tc.want)
		}
	}

	v2 := t.TempDir()
	writeFile(t, filepath.Join(v2, "project.yaml"), v2ProjectYAML)
	root := t.TempDir()
	if err := WriteMarker(root, Marker{Jig: "1", Project: "demo", Kind: KindProject, Publish: &Publish{Trailer: "x"}}); err != nil {
		t.Fatal(err)
	}
	cfg, err := LoadConfig(jigHome, v2, "demo", root)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.PublishTrailer != "" {
		t.Errorf("a v2 store: PublishTrailer = %q, want empty: a v2 store takes nothing from a marker", cfg.PublishTrailer)
	}
}

// TestMarkerReadsThePublishTrailerFromYAML: the key is read from the file as a
// project writes it, and a marker without it reads as none.
func TestMarkerReadsThePublishTrailerFromYAML(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, MarkerFile)
	writeFile(t, path, "jig: \"1\"\nproject: demo\nkind: project\npublish:\n  trailer: |\n    line one\n    line two\n")
	m, err := LoadMarker(path)
	if err != nil {
		t.Fatal(err)
	}
	if m.Publish == nil || m.Publish.Trailer != "line one\nline two\n" {
		t.Errorf("Publish = %+v, want the two-line trailer", m.Publish)
	}
	writeFile(t, path, "jig: \"1\"\nproject: demo\nkind: project\n")
	if m, err = LoadMarker(path); err != nil || m.Publish != nil {
		t.Errorf("a marker without publish: Publish = %+v (err %v), want nil", m.Publish, err)
	}
}

// TestConfigTakesMarker: a marker is the store's project's only for a v3
// store, when it is not a member's and when the store serves its project (or
// names none, or the marker names none).
func TestConfigTakesMarker(t *testing.T) {
	t.Parallel()
	v3 := Config{SchemaVersion: 3, Projects: []string{"demo"}}
	for name, tc := range map[string]struct {
		cfg  Config
		m    Marker
		want bool
	}{
		"a project the store serves":     {v3, Marker{Project: "demo", Kind: KindProject}, true},
		"a marker naming no project":     {v3, Marker{Kind: KindProject}, true},
		"a store naming no projects":     {Config{SchemaVersion: 3}, Marker{Project: "other", Kind: KindProject}, true},
		"an orchestrator":                {v3, Marker{Project: "demo", Kind: KindOrchestrator}, true},
		"a member marker":                {v3, Marker{Project: "demo", Kind: KindMember}, false},
		"another project's marker":       {v3, Marker{Project: "other", Kind: KindProject}, false},
		"a v2 store":                     {Config{SchemaVersion: 2, Projects: []string{"demo"}}, Marker{Project: "demo", Kind: KindProject}, false},
		"a store with no schema version": {Config{}, Marker{Project: "demo", Kind: KindProject}, false},
	} {
		if got := tc.cfg.TakesMarker(tc.m); got != tc.want {
			t.Errorf("%s: TakesMarker = %v, want %v", name, got, tc.want)
		}
	}
}
