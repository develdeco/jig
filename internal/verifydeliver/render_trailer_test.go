package verifydeliver

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/develdeco/jig/internal/fixture"
	"github.com/develdeco/jig/internal/stack"
)

// TestPRBodyEndsWithTheProjectsTrailer: a project whose jig.yaml sets a trailer
// has every rendered body end with it, after the Verification section, one
// blank line before it and a final newline; CRLF reads as LF, surrounding
// whitespace is trimmed and a multi-line trailer keeps its lines. Without a
// trailer (empty, blank or none) the body is byte for byte what it was.
func TestPRBodyEndsWithTheProjectsTrailer(t *testing.T) {
	t.Parallel()
	fx := fixture.Generate(t, fixture.Opts{Home: t.TempDir()})
	d := newDeps(t, fx)

	const what = "- changes the greeting\n"
	oracles := []string{"test"}
	rounds := []RoundRecord{{Round: 1, Verdict: RoundClean, Scope: "full"}}
	rep := reportYAML{}
	base := renderWhatSection(what) + renderVerificationSection(rep, oracles, nil, rounds)

	render := func(trailer string) string {
		t.Helper()
		rel, _, err := writePRBody(d.Store, fx.Ticket, "fixture-repo", what, rep, oracles, nil, rounds, nil, nil, stack.Repo{}, trailer)
		if err != nil {
			t.Fatalf("writePRBody: %v", err)
		}
		data, err := os.ReadFile(filepath.Join(d.Store.Root, filepath.FromSlash(rel)))
		if err != nil {
			t.Fatal(err)
		}
		return string(data)
	}

	for name, tc := range map[string]struct{ trailer, want string }{
		"one line":               {"Generated by an agent", base + "\nGenerated by an agent\n"},
		"surrounding whitespace": {"\n  Generated by an agent \t\n\n", base + "\nGenerated by an agent\n"},
		"crlf":                   {"line one\r\nline two\r\n", base + "\nline one\nline two\n"},
		"multi-line kept":        {"line one\n\n  line two", base + "\nline one\n\n  line two\n"},
		"empty leaves it as was": {"", base},
		"blank leaves it as was": {" \r\n\t\n", base},
	} {
		if got := render(tc.trailer); got != tc.want {
			t.Errorf("%s: body =\n%q\nwant\n%q", name, got, tc.want)
		}
	}
}
